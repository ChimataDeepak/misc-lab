-- Oracle dialect of db/migration/V2 + V3 (statement ledger + its read-path indexes).
CREATE TABLE ledger_receipts (
    id           NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payer_id     NUMBER(19)    NOT NULL,
    merchant     VARCHAR2(100) NOT NULL,
    amount_minor NUMBER(19)    NOT NULL CHECK (amount_minor > 0),
    currency     VARCHAR2(3)   NOT NULL,
    created_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL
);
CREATE TABLE ledger_receipt_lines (
    id           NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receipt_id   NUMBER(19)    NOT NULL REFERENCES ledger_receipts (id),
    description  VARCHAR2(200) NOT NULL,
    amount_minor NUMBER(19)    NOT NULL
);
CREATE INDEX ledger_receipts_payer_created_idx ON ledger_receipts (payer_id, created_at DESC, id DESC);
CREATE INDEX ledger_receipt_lines_receipt_idx ON ledger_receipt_lines (receipt_id);
